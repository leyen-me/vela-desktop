import fs from 'node:fs';
import path from 'node:path';
import { DSH_PATCH_DIR, ensureDshDirs } from './config.ts';

/**
 * Tools that can read or mutate the host machine are disabled: this runtime only
 * talks to the trading API through MCP, so a prompt-injected market headline cannot
 * turn into a shell command.
 */
const DISABLED_PLUGINS = [
  'tool-bash',
  'tool-pwsh',
  'tool-jobs',
  'tool-fs',
  'tool-fs-search',
  'tool-web',
  'tool-skill',
  'skill-filesystem',
  'skill',
  'agent-instructions',
  'tool-subagent',
  'tool-subagent-fork',
  'tool-subagent-control',
  'tool-subagent-list-agents',
  'subagent',
  'tool-workflow',
  'workflow-ptc',
  'ptc-runtime',
  'tool-plugin-manager',
  'plugin-manager',
  'hmr',
  'config-editor',
  'settings',
  'goal',
  'tool-goal',
  'command-goal',
  'plan-mode',
  'commands',
  'tool-todo',
  'tool-working-directory',
  'workspace-dependencies',
  'skill-office',
  'session-title',
  'session-title-llm',
  'user-questions',
  'mcp-resources',
] as const;

export type McpServerPatch = {
  id: string;
  serverName: string;
  command: string;
  args: string[];
  env?: Record<string, string>;
};

function quote(value: string): string {
  return JSON.stringify(value);
}

function renderMcpEntry(server: McpServerPatch): string[] {
  const lines = [
    `    - id: ${quote(server.id)}`,
    `      name: '@deepseek-ai/dsh-mcp-client'`,
    '      config:',
    `        serverName: ${quote(server.serverName)}`,
    '        transport: stdio',
    `        command: ${quote(server.command)}`,
    `        args: [${server.args.map(quote).join(', ')}]`,
    '        failOnStartupError: true',
  ];
  const env = Object.entries(server.env ?? {});
  if (env.length > 0) {
    lines.push('        env:');
    for (const [key, value] of env) lines.push(`          ${key}: ${quote(value)}`);
  }
  return lines;
}

export type PatchOptions = {
  personaPrefix?: string;
};

export function buildPatch(servers: McpServerPatch[], options: PatchOptions = {}): string {
  const lines = ['# Generated by apps/web/server/dsh/patch.ts. Do not edit by hand.'];
  for (const id of DISABLED_PLUGINS) {
    lines.push(`- id: ${id}`, '  disabled: true');
  }
  if (options.personaPrefix) {
    lines.push('- id: system-prompt', '  config:', `    personaPrefix: ${quote(options.personaPrefix)}`);
  }
  if (servers.length > 0) {
    lines.push('- insert:');
    for (const server of servers) lines.push(...renderMcpEntry(server));
  }
  return `${lines.join('\n')}\n`;
}

export function writePatch(fileName: string, servers: McpServerPatch[], options: PatchOptions = {}): string {
  ensureDshDirs();
  const target = path.join(DSH_PATCH_DIR, fileName);
  fs.writeFileSync(target, buildPatch(servers, options), 'utf8');
  return target;
}

export function removePatch(target: string): void {
  try {
    fs.rmSync(target, { force: true });
  } catch {
    /* best-effort cleanup */
  }
}
